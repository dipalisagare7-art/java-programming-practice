package loops;
public class CheckNumber1 {
    public static void main(String[] args) {
        int i = -10;
        if (i > 0) {
            System.out.println("i is positive:");
        } else if (i < 0) {
            System.out.println("i is negative:");
        } else {
            System.out.println("i is zero:");
        }
    }
}
