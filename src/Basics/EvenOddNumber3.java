package Basics;

public class EvenOddNumber3 {
        public static void main(String[] args) {

            for (int i = 1; i <= 6; i++) {
                if (i % 2 == 0) {
                    System.out.print("from 1 to 6" );
                } else {
                    System.out.println("from 6 to 1");
                }
            }
        }
    }

